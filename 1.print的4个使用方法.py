print("What " + "can " + "I "+ "say?")
# +号能同时打印多个字符串
# 注意：+号只能连接类型为「字符串」的数据
# 若要使用+号则要使用str()函数将其他类型的数据转为字符串

print("Hello", "world")
# 也可以用逗号分隔字符串，这种情况下无+号的限制

print("She said \"Let\' go!\"")
# / 反斜杠转义符，使程序能够区分引号内的引号

print("Hello\nHi!")
# \n 适用于单个回车

print('''春江潮水连海平，
海上明月共潮生。
滟滟随波千万里，
何处春江无月明。
……''')
# 三对单或双引号可用于多行回车打印